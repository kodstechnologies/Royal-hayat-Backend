  Pediatric: "Pediatrics",
  "General Surgery": "General & Laparoscopic Surgery",
  "La Cosmetique": "Plastic Surgery & Cosmetology",
  Dental: "Dental Clinic",
  Pharmacy: "Royale Hayat Pharmacy",
